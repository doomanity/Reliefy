package com.doomanity.cooley.video.stream

/**
 * One audio or video stream of a video, in the shape LibreTube's player code expects
 * (ported from LibreTube's `PipedStream`, trimmed to the fields that code reads).
 */
data class PipedStream(
    var url: String? = null,
    val format: String? = null,
    val quality: String? = null,
    val mimeType: String? = null,
    val codec: String? = null,
    val videoOnly: Boolean? = null,
    val bitrate: Int? = null,
    val initStart: Int? = null,
    val initEnd: Int? = null,
    val indexStart: Int? = null,
    val indexEnd: Int? = null,
    val width: Int? = null,
    val height: Int? = null,
    val fps: Int? = null,
    val durationMs: Long? = null,
    val audioTrackName: String? = null,
    val audioTrackId: String? = null,
    val contentLength: Long = -1,
    val audioTrackType: String? = null,
    val audioTrackLocale: String? = null,
    val itag: Int? = null,
    val lastModified: Long? = null,
    val isDrc: Boolean? = null,
    val xtags: String? = null,
)

data class SubtitleTrack(
    val url: String?,
    val mimeType: String?,
    val name: String?,
    val code: String?,
    val autoGenerated: Boolean,
)

/** Everything needed to play one video (ported from LibreTube's `Streams`, trimmed). */
data class Streams(
    val duration: Long,
    val isLive: Boolean,
    val hls: String?,
    val dash: String?,
    val audioStreams: List<PipedStream>,
    val videoStreams: List<PipedStream>,
    val subtitles: List<SubtitleTrack>,
    val serverAbrStreamingUrl: String?,
    val videoPlaybackUstreamerConfig: String?,
)
