private const val TAG = "VideoStreams"

/** A video's streams plus what the watch page shows about it. */
class LoadedVideo(
    val streams: Streams,
    val details: VideoDetails,
)

/**
 * Reads a video the way LibreTube does: NewPipe Extractor (LibreTube's fork) with a PoToken from
 * BotGuard, which gives SABR streaming data, plain DASH streams as a fallback, and HLS for lives.
 */
object StreamFetcher {
    @Volatile
    private var ready = false

    fun ensureReady() = ensureNewPipe()

    private fun ensureNewPipe() {
        if (ready) return
        synchronized(this) {
            if (ready) return
            // The music side may have set NewPipe up already (it shares this extractor for its
            // last fallback). Keep its downloader if so; only the PoToken provider is ours.
            if (NewPipe.getDownloader() == null) NewPipe.init(OkHttpDownloader())
            YoutubeStreamExtractor.setPoTokenProvider(PoTokenGenerator.shared)
            ready = true
        }
    }

    suspend fun load(videoId: String): LoadedVideo =
        withContext(Dispatchers.IO) {
            ensureNewPipe()
            val info = StreamInfo.getInfo("https://www.youtube.com/watch?v=$videoId")
            val isLive =
                info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM
            val streams =
                Streams(
                    duration = info.duration,
                    isLive = isLive,
                    hls = info.hlsUrl?.takeIf { it.isNotBlank() },
                    dash = info.dashMpdUrl?.takeIf { it.isNotBlank() },
                    audioStreams = info.audioStreams.map { it.toPipedStream() },
                    videoStreams = info.videoOnlyStreams.map { it.toPipedStream() },
                    subtitles =
                        info.subtitles.map {
                            SubtitleTrack(
                                url = it.content,
                                mimeType = it.format?.mimeType,
                                name = it.displayLanguageName,
                                code = it.languageTag,
                                autoGenerated = it.isAutoGenerated,
                            )
                        },
                    serverAbrStreamingUrl = info.serverAbrStreamingUrl,
                    videoPlaybackUstreamerConfig = info.ustreamerConfig,
                )
            val details =
                VideoDetails(
                    videoId = videoId,
                    title = info.name,
                    description = info.description.toPlainText(),
                    channelId = info.uploaderUrl?.toYoutubeId(),
                    channelName = info.uploaderName,
                    channelAvatarUrl = info.uploaderAvatars.best(),
                    channelVerified = info.isUploaderVerified,
                    subscriberCount = info.uploaderSubscriberCount,
                    viewCount = info.viewCount,
                    likeCount = info.likeCount,
                    uploadedText =
                        info.uploadDate?.let { runCatching { relativeTime(it.offsetDateTime()) }.getOrNull() }
                            ?: info.textualUploadDate,
                    durationSeconds = info.duration,
                    isLive = isLive,
                    isShort =
                        info.isShortFormContent ||
                            (info.videoOnlyStreams.firstOrNull()?.let { it.height > it.width } ?: false),
                    thumbnailUrl = info.thumbnails.best(),
                    related = info.relatedItems.mapNotNull { it.toVideoItem() },
                    chapters =
                        info.streamSegments.map {
                            VideoChapter(title = it.title, startMs = it.startTimeSeconds * 1000L)
                        },
                )
            Logger.d(
                TAG,
                "loaded $videoId sabr=${streams.serverAbrStreamingUrl != null} " +
                    "audio=${streams.audioStreams.size} video=${streams.videoStreams.size} live=$isLive",
            )
            LoadedVideo(streams, details)
        }
}

private fun Description?.toPlainText(): String {
    val content = this?.content.orEmpty()
    return if (this?.type == Description.Type.HTML) {
        HtmlCompat.fromHtml(content, HtmlCompat.FROM_HTML_MODE_LEGACY).toString().trim()
    } else {
        content.trim()
    }
}

private fun List<Image>.best(): String? = maxByOrNull { it.height }?.url

/** "https://www.youtube.com/watch?v=ID" -> ID, "https://www.youtube.com/channel/UC.." -> UC.. */
internal fun String.toYoutubeId(): String {
    Regex("[?&]v=([^&#]+)").find(this)?.let { return it.groupValues[1] }
    return substringBefore('?').trimEnd('/').substringAfterLast('/')
}

private fun InfoItem.toVideoItem(): VideoItem? {
    if (this !is StreamInfoItem) return null
    val live = streamType == StreamType.LIVE_STREAM || streamType == StreamType.AUDIO_LIVE_STREAM
    return VideoItem(
        videoId = url.toYoutubeId(),
        title = name,
        channelName = uploaderName,
        channelId = uploaderUrl?.toYoutubeId(),
        channelAvatarUrl = uploaderAvatars.best(),
        thumbnailUrl = thumbnails.best(),
        durationText = if (live || duration <= 0) null else formatDuration(duration),
        viewsText = viewCount.takeIf { it >= 0 }?.let { "${compactCount(it)} views" },
        publishedText = uploadDate?.let { runCatching { relativeTime(it.offsetDateTime()) }.getOrNull() } ?: textualUploadDate,
        isLive = live,
        isShort = isShortFormContent,
    )
}

/** 338 -> "5:38", 3882 -> "1:04:42". */
fun formatDuration(seconds: Long): String {
    val h = seconds / 3600
    val m = (seconds % 3600) / 60
    val s = seconds % 60
    return if (h > 0) String.format(Locale.US, "%d:%02d:%02d", h, m, s) else String.format(Locale.US, "%d:%02d", m, s)
}

/** 1234 -> "1.2K", 5_600_000 -> "5.6M". */
fun compactCount(n: Long): String {
    fun one(v: Double, suffix: String): String {
        val text = if (v >= 100 || v % 1.0 < 0.05) v.toLong().toString() else String.format(Locale.US, "%.1f", v)
        return text + suffix
    }
    return when {
        n >= 1_000_000_000 -> one(n / 1_000_000_000.0, "B")
        n >= 1_000_000 -> one(n / 1_000_000.0, "M")
        n >= 1_000 -> one(n / 1_000.0, "K")
        else -> n.toString()
    }
}

private fun VideoStream.toPipedStream() =
    PipedStream(
        url = content,
        codec = codec,
        format = format?.toString(),
        height = height,
        width = width,
        quality = getResolution(),
        mimeType = format?.mimeType,
        bitrate = bitrate,
        initStart = initStart,
        initEnd = initEnd,
        indexStart = indexStart,
        indexEnd = indexEnd,
        fps = fps,
        durationMs = itagItem?.approxDurationMs,
        contentLength = itagItem?.contentLength ?: 0L,
        itag = itagItem?.id,
        lastModified = itagItem?.lastModified,
        xtags = itagItem?.xtags,
        videoOnly = true,
    )

private fun AudioStream.toPipedStream() =
    PipedStream(
        url = content,
        format = format?.toString(),
        quality = "$averageBitrate bits",
        bitrate = bitrate,
        mimeType = format?.mimeType,
        initStart = initStart,
        initEnd = initEnd,
        indexStart = indexStart,
        indexEnd = indexEnd,
        durationMs = itagItem?.approxDurationMs,
        contentLength = itagItem?.contentLength ?: 0L,
        codec = codec,
        audioTrackId = audioTrackId,
        audioTrackName = audioTrackName,
        audioTrackLocale = audioLocale?.toLanguageTag(),
        audioTrackType = audioTrackType?.name,
        videoOnly = false,
        itag = itagItem?.id,
        lastModified = itagItem?.lastModified,
        isDrc = itagItem?.isDrc,
        xtags = itagItem?.xtags,
    )

/** NewPipe's network layer, used only if nothing set one up before (LibreTube's downloader). */
private class OkHttpDownloader : Downloader() {
    private val client = OkHttpClient.Builder().build()

    @Throws(IOException::class, ReCaptchaException::class)
    override fun execute(request: Request): Response {
        val builder =
            okhttp3.Request
                .Builder()
                .method(request.httpMethod(), request.dataToSend()?.toRequestBody())
                .url(request.url())
                .addHeader("User-Agent", USER_AGENT)
        for ((key, values) in request.headers()) {
            builder.removeHeader(key)
            for (value in values) builder.addHeader(key, value)
        }
        val response = client.newCall(builder.build()).execute()
        if (response.code == 429) {
            response.close()
            throw ReCaptchaException("reCaptcha Challenge requested", request.url())
        }
        val body = response.body.string()
        return Response(response.code, response.message, response.headers.toMultimap(), body, response.request.url.toString())
    }

    private companion object {
        const val USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:135.0) Gecko/20100101 Firefox/135.0"
    }
}
